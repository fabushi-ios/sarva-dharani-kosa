/**
 * scripts/build-cjk-phonetic-fold.mjs
 *
 * Generates src/core/search/generated/cjkPhoneticFold.ts from the Unicode Unihan database
 * (kMandarin readings). Every CJK character is mapped to ONE representative character per
 * toneless Mandarin syllable, so search compares Chinese text by *sound*:
 *
 *  - Traditional / Simplified (羅/罗, 馱/驮, 堅/坚) share a reading → fold together;
 *  - dhāraṇī transliteration variants (儞/你, 陁/陀, 囉/啰, 嚩/缚) are by nature phonetic
 *    spellings of the same Sanskrit syllable → fold together;
 *  - homophone typos (帝天/地天) → fold together.
 *
 * No hand-written character lists: the table is derived entirely from Unihan.
 * Usage: node scripts/build-cjk-phonetic-fold.mjs   (downloads Unihan.zip if not cached)
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const CACHE_DIR = 'data/raw/unihan';
const ZIP = path.join(CACHE_DIR, 'Unihan.zip');
const OUT = 'src/core/search/generated/cjkPhoneticFold.ts';

fs.mkdirSync(CACHE_DIR, { recursive: true });
if (!fs.existsSync(ZIP)) {
  const res = await fetch('https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip');
  if (!res.ok) throw new Error(`Unihan download failed: HTTP ${res.status}`);
  fs.writeFileSync(ZIP, Buffer.from(await res.arrayBuffer()));
}
const readFromZip = (name) =>
  execFileSync('python3', ['-c', `import zipfile,sys;sys.stdout.write(zipfile.ZipFile(${JSON.stringify(ZIP)}).read(${JSON.stringify(name)}).decode())`], {
    maxBuffer: 1 << 28,
  }).toString();

const readings = readFromZip('Unihan_Readings.txt');
const otherMappings = readFromZip('Unihan_OtherMappings.txt');

const inGb2312 = new Set();
for (const line of otherMappings.split('\n')) {
  const m = line.match(/^U\+([0-9A-F]+)\tkGB0\t/);
  if (m) inGb2312.add(parseInt(m[1], 16));
}

const toneless = (py) =>
  py
    .normalize('NFD')
    .replace(/u\u0308/g, 'v')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();

/** syllable -> code points */
const groups = new Map();
for (const line of readings.split('\n')) {
  const m = line.match(/^U\+([0-9A-F]+)\tkMandarin\t(\S+)/);
  if (!m) continue;
  const cp = parseInt(m[1], 16);
  const syl = toneless(m[2]); // first (most common) reading
  if (!groups.has(syl)) groups.set(syl, []);
  groups.get(syl).push(cp);
}

// Representative: the most "standard" member — a GB2312 character if any, lowest code point.
const lines = [];
let total = 0;
for (const [syl, cps] of [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  cps.sort((a, b) => (inGb2312.has(b) - inGb2312.has(a)) || a - b);
  const rep = String.fromCodePoint(cps[0]);
  const members = cps.slice(1).map((c) => String.fromCodePoint(c)).join('');
  total += cps.length;
  lines.push(`${syl}:${rep}${members}`);
}

const out = `// AUTO-GENERATED by scripts/build-cjk-phonetic-fold.mjs from Unicode Unihan (kMandarin, kGB0).
// DO NOT EDIT. ${groups.size} toneless syllables, ${total} characters.
// Format: "syllable:<representative><members…>" per line.
export const CJK_PHONETIC_GROUPS = ${JSON.stringify(lines.join('\n'))};
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${groups.size} syllables, ${total} chars, ${(out.length / 1024).toFixed(0)} KB`);
